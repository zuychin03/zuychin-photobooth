import { createHash } from "node:crypto";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import sharp from "sharp";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceRoot = path.join(root, "docs/assets/v2");
const source = JSON.parse(await readFile(path.join(sourceRoot, "asset-index.json"), "utf8"));
const hash = bytes => createHash("sha256").update(bytes).digest("hex");
const version = "2.0.0";
const assets = [];
const colours = { "ivory-cotton-paper-v2": "#eee5d5", "rose-washi-paper-v2": "#e6b8be", "indigo-bookcloth-v2": "#243247", "champagne-brushed-metal-v2": "#ddcaa4", "charcoal-photo-paper-v2": "#29292c", "pearl-iridescent-film-v2": "#e9e2ee" };
const fallbacks = { "rooftop-blue-hour-v2": "night", "coastal-picnic-v2": "beach", "lantern-courtyard-v2": "sunset", "midnight-disco-v2": "night", "rainy-cafe-v2": "night", "candy-cloud-studio-v2": "studio-rose", "birthday-confetti-v2": "studio-rose" };
const focalOverrides = Object.fromEntries([
  "paper-moon-studio-v2", "porcelain-sculpture-studio-v2", "lantern-courtyard-v2",
  "lilac-origami-v2", "liquid-chrome-v2", "film-noir-lobby-v2",
  "graduation-atelier-v2", "winter-celebration-v2", "birthday-confetti-v2",
].map(id => [id, [0.75, 0.5]]));
sharp.concurrency(1);
for (const item of source.assets) {
  if (!/^(scenes|materials)\/[a-z0-9-]+\.png$/.test(item.file)) throw new Error("Unsafe source path");
  const original = await readFile(path.join(sourceRoot, item.file));
  if (hash(original) !== item.sha256 || original.length !== item.bytes) throw new Error(`Changed source: ${item.id}`);
  const metadata = await sharp(original).metadata();
  if (metadata.width !== item.width || metadata.height !== item.height || metadata.pages > 1) throw new Error(`Changed dimensions: ${item.id}`);
  const kind = item.category === "material" ? "material" : "scene";
  const directory = `${kind === "scene" ? "scenes" : "materials"}/v2`;
  await mkdir(path.join(root, "public", directory), { recursive: true });
  const variants = {};
  for (const [variant, edge, quality] of [["full", kind === "scene" ? 1536 : 1024, kind === "scene" ? 86 : 90], ["thumbnail", 320, 76]]) {
    const bytes = await sharp(original).rotate().resize({ width: edge, height: edge, fit: "inside", withoutEnlargement: true }).toColourspace("srgb").webp({ quality, effort: 6, smartSubsample: true }).toBuffer();
    const output = await sharp(bytes).metadata(), sha256 = hash(bytes);
    if (bytes.length > (variant === "full" ? 1024 * 1024 : 64 * 1024)) throw new Error(`Delivery budget exceeded: ${item.id}/${variant}`);
    const file = `${item.id}.${variant}.${sha256.slice(0, 12)}.webp`;
    await writeFile(path.join(root, "public", directory, file), bytes);
    variants[variant] = { path: `/${directory}/${file}`, width: output.width, height: output.height, bytes: bytes.length, sha256 };
  }
  assets.push({ id: item.id, name: item.name, version, kind, category: item.category, ...variants, focalPoint: focalOverrides[item.id] ?? item.focalPoint, crop: "cover", fallback: { sceneId: fallbacks[item.id] ?? "studio-cream", colour: colours[item.id] ?? "#eee5d5" }, provenance: { file: `docs/assets/v2/${item.provenance}`, source: `docs/assets/v2/${item.file}`, sha256: item.sha256 }, captionTone: ["indigo-bookcloth-v2", "charcoal-photo-paper-v2"].includes(item.id) ? "light" : "dark" });
}
const manifest = { version, assets };
await mkdir(path.join(root, "lib/assets"), { recursive: true });
await writeFile(path.join(root, "lib/assets/manifest.json"), JSON.stringify(manifest, null, 2) + "\n");
const packs = assets.map(asset => ({ category: asset.category, files: [asset.full, asset.thumbnail] }));
await writeFile(path.join(root, "public/scenes/v2/pack-index.js"), `/* Generated by scripts/prepare-v2-assets.mjs. */\nself.PB_ASSET_PACK = ${JSON.stringify({ version, packs })};\n`);
console.log(JSON.stringify({ assets: assets.length, originalBytes: source.assets.reduce((sum, item) => sum + item.bytes, 0), fullBytes: assets.reduce((sum, item) => sum + item.full.bytes, 0), thumbnailBytes: assets.reduce((sum, item) => sum + item.thumbnail.bytes, 0), largestFull: Math.max(...assets.map(item => item.full.bytes)), largestThumbnail: Math.max(...assets.map(item => item.thumbnail.bytes)) }, null, 2));
